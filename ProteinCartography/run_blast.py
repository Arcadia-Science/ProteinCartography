#!/usr/bin/env python
import argparse
import sys
import time

import blast_utils
import constants


def parse_args():
    """
    Define CLI arguments for the subset of `blastp` arguments that are used by the `run_blast` rule
    following the nomenclature of the `blastp` CLI

    Note: `--timeout_seconds` and `--email` have no `blastp` equivalent; they exist because the
    search is submitted to NCBI's URL API rather than being run by the `blastp` CLI.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--query", required=True, help="path to the input peptide FASTA file.")
    parser.add_argument(
        "--out",
        required=True,
        help="path to the blastresults.tsv file generated by blastp.",
    )
    parser.add_argument(
        "--outfmt",
        default=constants.BLAST_OUTFMT,
        help="query format string.",
    )
    parser.add_argument(
        "--max_target_seqs",
        type=int,
        required=True,
        help="maximum number of hits to return.",
    )
    parser.add_argument(
        "--word_size",
        type=int,
        required=True,
    )
    parser.add_argument(
        "--word_size_backoff",
        type=int,
        required=True,
        help="word size to which to back off if the initial call to blastp fails.",
    )
    parser.add_argument(
        "--num_attempts",
        type=int,
        required=True,
        help="The number of times to try calling blastp before exiting with an error.",
    )
    parser.add_argument(
        "--evalue",
        type=float,
        required=True,
    )
    parser.add_argument(
        "--timeout_seconds",
        type=float,
        required=True,
        help=(
            "the total time to spend waiting for NCBI, across all attempts, before giving up. "
            "Retrying does not reset this budget."
        ),
    )
    parser.add_argument(
        "--email",
        default=None,
        help=(
            "the contact email address to send to NCBI, which NCBI asks automated clients to "
            f"provide. Overridden by the '{blast_utils.EMAIL_ENV_VAR}' env variable."
        ),
    )
    args = parser.parse_args()

    return args


def main():
    args = parse_args()

    # The timeout is a budget for the whole rule rather than for one attempt: it is established
    # once, here, and every attempt draws down the same deadline. Giving each attempt its own
    # timeout would mean that the worst case is `num_attempts` times as long as the configured
    # value, which is what the user actually waits for.
    started_at = time.monotonic()
    deadline = started_at + args.timeout_seconds

    result = None
    num_tries = 0
    while num_tries < args.num_attempts:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break

        word_size = args.word_size if num_tries == 0 else args.word_size_backoff
        print(
            f"Attempt {num_tries + 1}/{args.num_attempts} to run a blast search "
            f"(using a word size of {word_size}, with {round(remaining)}s of the "
            f"{round(args.timeout_seconds)}s budget remaining)"
        )
        result = blast_utils.run_blast(
            query=args.query,
            out=args.out,
            max_target_seqs=args.max_target_seqs,
            outfmt=args.outfmt,
            word_size=word_size,
            evalue=args.evalue,
            timeout_seconds=remaining,
            email=args.email,
        )
        if not blast_utils.blast_call_failed(result):
            sys.exit(0)

        num_tries += 1

    elapsed = round(time.monotonic() - started_at)
    last_error = (
        result.stderr
        if result is not None
        else "the timeout was already exhausted before any attempt could be made"
    )
    sys.exit(
        f"BLAST failed after {num_tries} attempt(s) and {elapsed}s of the "
        f"{round(args.timeout_seconds)}s total budget (set by the 'blast_timeout_seconds' "
        f"config parameter). The last error message was: {last_error}"
    )


if __name__ == "__main__":
    main()
